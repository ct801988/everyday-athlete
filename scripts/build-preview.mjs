import { Buffer } from "node:buffer";
import {
  readdirSync,
  readFileSync,
  writeFileSync,
  mkdirSync,
  cpSync,
  rmSync,
} from "node:fs";
import { createHash } from "node:crypto";
import { deflateSync } from "node:zlib";
const dir = ".data/preview-assets";
rmSync(dir, { recursive: true, force: true });
mkdirSync(dir, { recursive: true });
cpSync("dist", dir, { recursive: true });
// Deterministic neutral icons, not final branding or exercise media.
function crc(b) {
  let c = 0xffffffff;
  for (const x of b) {
    c ^= x;
    for (let n = 0; n < 8; n++) c = (c >>> 1) ^ (c & 1 ? 0xedb88320 : 0);
  }
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(name, b) {
  const t = Buffer.from(name),
    len = Buffer.alloc(4),
    sum = Buffer.alloc(4);
  len.writeUInt32BE(b.length);
  sum.writeUInt32BE(crc(Buffer.concat([t, b])));
  return Buffer.concat([len, t, b, sum]);
}
function icon(n) {
  const rows = [
    "111101110",
    "100001010",
    "111001110",
    "100001010",
    "111101010",
  ];
  const scale = Math.floor(n / 13),
    left = Math.floor((n - 9 * scale) / 2),
    top = Math.floor((n - 5 * scale) / 2);
  const data = Buffer.alloc(n * (1 + n * 3));
  for (let y = 0; y < n; y++)
    for (let x = 0; x < n; x++) {
      const col = Math.floor((x - left) / scale),
        row = Math.floor((y - top) / scale),
        on =
          row >= 0 && row < 5 && col >= 0 && col < 9 && rows[row][col] === "1";
      const i = y * (1 + n * 3) + 1 + x * 3;
      data[i] = on ? 255 : 18;
      data[i + 1] = on ? 255 : 60;
      data[i + 2] = on ? 255 : 70;
    }
  const head = Buffer.alloc(13);
  head.writeUInt32BE(n);
  head.writeUInt32BE(n, 4);
  head[8] = 8;
  head[9] = 2;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", head),
    chunk("IDAT", deflateSync(data)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}
mkdirSync(dir + "/icons");
for (const n of [180, 192, 512])
  writeFileSync(dir + "/icons/icon-" + n + ".png", icon(n));
const manifest = {
  id: "/",
  name: "Fitness App Preview",
  short_name: "Fitness App Preview",
  start_url: "/",
  scope: "/",
  display: "standalone",
  background_color: "#f2f5f5",
  theme_color: "#123c46",
  icons: [192, 512].map((n) => ({
    src: "/icons/icon-" + n + ".png",
    sizes: n + "x" + n,
    type: "image/png",
    purpose: "any",
  })),
};
writeFileSync(
  dir + "/manifest.webmanifest",
  JSON.stringify(manifest, null, 2) + "\n",
);
const html = readFileSync(dir + "/index.html", "utf8")
  .replace(
    /<title>.*?<\/title>/,
    "<title>Fitness App Preview</title>",
  )
  .replace(
    "</head>",
    '<link rel="manifest" href="/manifest.webmanifest"><link rel="apple-touch-icon" href="/icons/icon-180.png"><meta name="theme-color" content="#123c46"><meta name="robots" content="noindex,nofollow"></head>',
  );
writeFileSync(dir + "/index.html", html);
const assets = readdirSync(dir + "/assets").map((n) => "/assets/" + n);
const precache = [
  "/",
  "/index.html",
  ...assets,
  "/manifest.webmanifest",
  ...["180", "192", "512"].map((n) => "/icons/icon-" + n + ".png"),
];
const hash = createHash("sha256")
  .update(precache.map((p) => (p === "/" ? "" : readFileSync(dir + p))).join())
  .digest("hex")
  .slice(0, 16);
let sw = readFileSync(dir + "/sw.js", "utf8")
  .replace(/ea-shell-[a-f0-9]+/g, "ea-preview-shell-" + hash)
  .replaceAll("k.startsWith('ea-shell-')", "k.startsWith('ea-preview-shell-')")
  .replace(/const FILES=.*?;/, "const FILES=" + JSON.stringify(precache) + ";");
writeFileSync(dir + "/sw.js", sw);
const paths = [...precache, "/sw.js"];
writeFileSync(
  "preview/asset-paths.ts",
  "// Generated by build:preview; exact protected artifact allowlist. No secrets.\nexport const assetPaths=" +
    JSON.stringify(paths, null, 2) +
    " as const;\n",
);
const files = paths
  .filter((p) => p !== "/")
  .map((p) => ({
    path: p,
    bytes: readFileSync(dir + p).length,
    sha256: createHash("sha256")
      .update(readFileSync(dir + p))
      .digest("hex"),
  }));
mkdirSync("reports/preview-preparation", { recursive: true });
writeFileSync(
  "reports/preview-preparation/deployment-assets.json",
  JSON.stringify({ hash, files }, null, 2) + "\n",
);
console.log(
  "Prepared protected static payload:",
  files.length,
  "files; no hosting operation",
);
